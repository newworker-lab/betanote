// Writes THIRD_PARTY_NOTICES.md: every third-party component that ships with the app, with its
// licence text. Two kinds ship: the production npm packages (packaged under node_modules in
// app.asar) and the assets the build copies into dist/ (fonts, PDF.js, KaTeX). Run it after a
// dependency changes:  npm run notices   (npm run notices -- --check fails when the file is stale).
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const out = join(root, 'THIRD_PARTY_NOTICES.md');
// The app's name and executable, from its name file (core/app-name.json).
const appName = JSON.parse(readFileSync(join(root, 'core', 'app-name.json'), 'utf8'));
const npmCommand = process.platform === 'win32' ? 'npm.cmd' : 'npm';
const parseable = execFileSync(npmCommand, ['ls', '--omit=dev', '--all', '--parseable'], { cwd: root, encoding: 'utf8', shell: process.platform === 'win32' });
const licenceFiles = dir => existsSync(dir) ? readdirSync(dir).filter(f => /^(licen[cs]e|copying|notice)(\.|-|_|$)/i.test(f)).sort() : [];
const text = file => readFileSync(file, 'utf8').replace(/\r\n?/g, '\n').trim();
const fence = body => '```text\n' + body.replace(/```/g, "'''") + '\n```';

// Production packages, one entry per name@version.
const packages = new Map();
for (const dir of parseable.split(/\r?\n/).filter(Boolean)) {
  if (dir === root.replace(/[\\/]$/, '') || !existsSync(join(dir, 'package.json'))) continue;
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  // Native binaries installed per operating system (@napi-rs/canvas-linux-x64-gnu, …-win32-x64-msvc) share
  // their parent's licence; one entry stands for them, so the file is the same whichever system writes it.
  const platform = /^(@napi-rs\/canvas)-(linux|win32|darwin|android|freebsd)-/.exec(pkg.name);
  if (platform) { const key = `${platform[1]} platform binaries@${pkg.version}`; if (!packages.has(key)) packages.set(key, { name: `${platform[1]} (platform binaries)`, version: pkg.version, license: pkg.license || '(see parent)', source: '', files: [], note: `Native binaries of ${platform[1]} for each operating system, under the same licence as ${platform[1]} (above).` }); continue; }
  const key = `${pkg.name}@${pkg.version}`;
  if (packages.has(key)) continue;
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  packages.set(key, { name: pkg.name, version: pkg.version, license: pkg.license || (pkg.licenses || []).map(l => l.type).join(' OR ') || '(see licence file)', source: (pkg.homepage || repo || '').replace(/^git\+/, '').replace(/\.git$/, ''), files: licenceFiles(dir).map(f => join(dir, f)) });
}

// Assets copied into dist/ by scripts/build.mjs, with the licence files that cover them.
const nm = join(root, 'node_modules');
const assets = [
  { title: 'Noto Sans KR (fonts, via @fontsource/noto-sans-kr)', license: 'OFL-1.1', where: 'dist/fonts', files: [join(nm, '@fontsource/noto-sans-kr/LICENSE')] },
  { title: 'Noto Serif KR (fonts, via @fontsource/noto-serif-kr)', license: 'OFL-1.1', where: 'dist/fonts', files: [join(nm, '@fontsource/noto-serif-kr/LICENSE')] },
  { title: 'PDF.js standard fonts — Foxit', license: 'BSD-style (see text)', where: 'dist/pdfjs/standard_fonts', files: [join(nm, 'pdfjs-dist/standard_fonts/LICENSE_FOXIT')] },
  { title: 'PDF.js standard fonts — Liberation', license: 'OFL-1.1', where: 'dist/pdfjs/standard_fonts', files: [join(nm, 'pdfjs-dist/standard_fonts/LICENSE_LIBERATION')] },
  { title: 'PDF.js character maps (CMaps)', license: 'BSD-3-Clause (see text)', where: 'dist/pdfjs/cmaps', files: [join(nm, 'pdfjs-dist/cmaps/LICENSE')] },
].map(a => ({ ...a, files: a.files.filter(existsSync) }));

const pdfjs = [...packages.values()].find(p => p.name === 'pdfjs-dist');
const lines = [
  '# Third-party notices',
  '',
  `${appName.name} ships with the third-party components below. Each stays under its own licence, reproduced here;`,
  `the licence chosen for ${appName.name} itself does not apply to them.`,
  '',
  'This file is generated by `npm run notices` (`scripts/third-party-notices.mjs`). Do not edit it by hand.',
  '',
  '## Changes to third-party files',
  '',
  `- PDF.js${pdfjs ? ` ${pdfjs.version}` : ''} (\`pdfjs-dist\`, Apache-2.0): \`scripts/build.mjs\` copies \`web/pdf_viewer.mjs\` to \`dist/pdfjs/pdf_viewer.mjs\` with one change — the text layer's accessibility sort reads each element's box once instead of on every comparison (same order, fewer layout reads). Other PDF.js files are copied unchanged.`,
  '- CodeMirror and its Lezer packages (MIT) are bundled, unchanged, into `dist/live-editor.js` by esbuild.',
  '',
  '## Electron and Chromium',
  '',
  'Packaged builds include Electron (MIT) and Chromium with their own notices: `LICENSE` and `LICENSES.chromium.html` next to the `' + appName.id + '` executable.',
  '',
  '## Bundled assets',
  '',
];
for (const a of assets) {
  lines.push(`### ${a.title}`, '', `- Licence: ${a.license}`, `- In the app: \`${a.where}\``, '');
  for (const f of a.files) lines.push(`\`${relative(root, f).replace(/\\/g, '/')}\``, '', fence(text(f)), '');
}
lines.push('## npm packages (production)', '', '| Package | Version | Licence |', '| --- | --- | --- |');
const sorted = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
for (const p of sorted) lines.push(`| ${p.name} | ${p.version} | ${p.license} |`);
lines.push('');
for (const p of sorted) {
  lines.push(`### ${p.name} ${p.version}`, '', `- Licence: ${p.license}`, ...(p.source ? [`- Source: ${p.source}`] : []), '');
  if (p.note) lines.push(`_${p.note}_`, '');
  else if (!p.files.length) lines.push('_The package has no licence file; its licence is declared in its package.json._', '');
  for (const f of p.files) lines.push(fence(text(f)), '');
}
const content = lines.join('\n').replace(/\n{3,}/g, '\n\n') + '\n';
if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n?/g, '\n') : '';
  if (current !== content) { console.error('THIRD_PARTY_NOTICES.md is out of date: run npm run notices'); process.exit(1); }
  console.log('THIRD_PARTY_NOTICES.md is up to date.');
} else {
  writeFileSync(out, content);
  console.log(`Wrote THIRD_PARTY_NOTICES.md: ${packages.size} packages, ${assets.length} bundled assets.`);
}
